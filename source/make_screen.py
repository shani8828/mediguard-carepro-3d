"""Lay out the 2.8" TFT screen (320 x 240 px, the panel's real resolution) and convert each
colour layer into merged rectangles -> screen_ui.py (pure data, no dependencies).
Each pixel = 58/320 x 43/240 mm on the 58 x 43 mm active area."""
import os, sys, pprint
import numpy as np
import matplotlib
from PIL import Image, ImageDraw, ImageFont

PW, PH = 320, 240
FD = os.path.join(matplotlib.get_data_path(), "fonts", "ttf")
REG, BOLD = os.path.join(FD, "DejaVuSans.ttf"), os.path.join(FD, "DejaVuSans-Bold.ttf")

# ---- screen content (example values) ----
MED_NAME = "Metformin"
MED_SUB = "500 mg tablet"
DOSE = "1 Tablet"
TIME_OF_DAY = "MORNING"
DATE = "Tue, 27 Oct 2026"
TIME = "08:00 AM"
DRAWER = "3"

# colours (RGB 0..1) and raise height of each layer above the glass (mm)
C_BAND = (0.11, 0.20, 0.34)
C_WHITE = (0.97, 0.97, 0.97)
C_GREY = (0.62, 0.70, 0.78)
C_AMBER = (0.98, 0.70, 0.16)
C_INK = (0.06, 0.10, 0.18)
C_GREEN = (0.35, 0.85, 0.50)

layers = []  # (name, colour, z0, z1, mask)


def new():
    im = Image.new("L", (PW, PH), 0)
    return im, ImageDraw.Draw(im)


def font(p, s):
    return ImageFont.truetype(p, s)


def text(d, xy, s, f, anchor="la", spacing=0):
    if spacing:
        x, y = xy
        for ch in s:
            d.text((x, y), ch, font=f, fill=255, anchor=anchor)
            x += d.textlength(ch, font=f) + spacing
    else:
        d.text(xy, s, font=f, fill=255, anchor=anchor)


def push(name, col, z, im):
    m = np.array(im) > 110
    layers.append((name, col, z, m))


# status bar band + divider + chip (background shapes, low layer)
im, d = new(); d.rectangle([0, 0, PW - 1, 31], fill=255); push("Screen_Status_Bar", C_BAND, 0, im)
im, d = new(); d.rectangle([12, 168, PW - 13, 169], fill=255); d.rectangle([215, 178, 216, 230], fill=255)
push("Screen_Dividers", C_BAND, 0, im)
fchip = font(BOLD, 15)
im, d = new()
cw = 34 + d.textlength(TIME_OF_DAY + " DOSE", font=fchip) + 14
d.rounded_rectangle([12, 42, 12 + cw, 68], radius=12, fill=255); push("Screen_TimeOfDay_Chip", C_AMBER, 0, im)

# text layers (raised above the shapes)
im, d = new(); text(d, (12, 16), DATE, font(REG, 15), "lm"); push("Screen_Date", C_GREY, 1, im)
im, d = new(); text(d, (PW - 12, 16), TIME, font(BOLD, 18), "rm"); push("Screen_Time", C_WHITE, 1, im)
im2, d2 = new(); d2.ellipse([24, 51, 32, 59], fill=255)
for k in range(8):
    a = k * np.pi / 4; cx, cy = 28, 55
    d2.line([cx + 7 * np.cos(a), cy + 7 * np.sin(a), cx + 10 * np.cos(a), cy + 10 * np.sin(a)], fill=255, width=2)
text(d2, (44, 56), TIME_OF_DAY + " DOSE", fchip, "lm"); push("Screen_TimeOfDay_Text", C_INK, 1, im2)
im, d = new(); text(d, (12, 76), MED_NAME, font(BOLD, 44)); push("Screen_Medicine_Name", C_WHITE, 1, im)
im, d = new(); text(d, (14, 132), MED_SUB, font(REG, 19)); push("Screen_Medicine_Strength", C_GREY, 1, im)
im, d = new(); text(d, (14, 178), "DOSE", font(BOLD, 12), spacing=2); text(d, (230, 178), "DRAWER", font(BOLD, 12), spacing=1)
push("Screen_Labels", C_GREY, 1, im)
im, d = new(); text(d, (14, 196), DOSE, font(BOLD, 30)); push("Screen_Dose", C_GREEN, 1, im)
im, d = new(); text(d, (230, 196), DRAWER, font(BOLD, 30)); push("Screen_Drawer_No", C_WHITE, 1, im)
layers = [L for L in layers if L[3].any()]


def rects(mask):
    """row runs merged downward into rectangles (c0, r0, c1, r1), end-exclusive"""
    out, open_ = [], {}
    for r in range(PH + 1):
        row = mask[r] if r < PH else np.zeros(PW, bool)
        runs, c = set(), 0
        while c < PW:
            if row[c]:
                s = c
                while c < PW and row[c]:
                    c += 1
                runs.add((s, c))
            c += 1
        for k in list(open_):
            if k not in runs:
                out.append((k[0], open_.pop(k), k[1], r))
        for k in runs:
            open_.setdefault(k, r)
    return out


if __name__ == "__main__":
    outdir = sys.argv[1] if len(sys.argv) > 1 else "."
    data = []
    for name, col, z, m in layers:
        data.append(dict(name=name, color=col, level=z, rects=rects(m)))
    with open("screen_ui.py", "w") as f:
        f.write("# Generated by make_screen.py: 320x240 TFT screen layout as merged pixel rectangles\n")
        f.write("# rect = (col0, row0, col1, row1) end-exclusive, row 0 = top of screen\n")
        f.write("UI_PX = (320, 240)\nUI_LAYERS = " + pprint.pformat(data, width=200, compact=True) + "\n")
    # flat preview of the layout
    img = np.zeros((PH, PW, 3)); img[:] = (0.04, 0.09, 0.17)
    for L in sorted(data, key=lambda L: L["level"]):
        for c0, r0, c1, r1 in L["rects"]:
            img[r0:r1, c0:c1] = L["color"]
    Image.fromarray((img * 255).astype(np.uint8)).resize((PW * 3, PH * 3), Image.NEAREST).save(f"{outdir}/screen_layout.png")
    print({L["name"]: len(L["rects"]) for L in data}, sum(len(L["rects"]) for L in data))
